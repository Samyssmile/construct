import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(scriptDir, '..');
const componentsDir = path.join(rootDir, 'components');
const standaloneDir = path.join(rootDir, 'standalone');
const checkOnly = process.argv.includes('--check');

const importPattern = /@import\s+['"]\.\/([^'"]+\.css)['"]\s*;/g;
const indexCss = fs.readFileSync(path.join(componentsDir, 'index.css'), 'utf8');
const componentFiles = [...indexCss.matchAll(importPattern)]
  .map((match) => match[1])
  .filter((file) => !file.startsWith('_'));

if (new Set(componentFiles).size !== componentFiles.length) {
  throw new Error('components/index.css imports a public component more than once.');
}

const generatedHeader = '/* Generated by scripts/build-standalone-components.mjs. Do not edit directly. */';
const expected = new Map([
  [
    'core.css',
    [
      generatedHeader,
      "@import '../tokens/tokens.css';",
      "@import '../components/_shared.css';",
      "@import '../components/_keyframes.css';",
      '',
    ].join('\n'),
  ],
  ...componentFiles.map((file) => [
    file,
    [
      generatedHeader,
      "@import './core.css';",
      `@import '../components/${file}';`,
      ...(['app-shell.css', 'app-shell-v2.css'].includes(file)
        ? ["@import '../components/_shell-shared.css';"]
        : []),
      '',
    ].join('\n'),
  ]),
]);

const currentFiles = fs.existsSync(standaloneDir)
  ? fs.readdirSync(standaloneDir).filter((file) => file.endsWith('.css')).sort()
  : [];
const expectedFiles = [...expected.keys()].sort();
const staleFiles = currentFiles.filter((file) => !expected.has(file));
const missingOrOutdated = expectedFiles.filter((file) => {
  const outputPath = path.join(standaloneDir, file);
  return !fs.existsSync(outputPath) || fs.readFileSync(outputPath, 'utf8') !== expected.get(file);
});

if (checkOnly) {
  if (staleFiles.length || missingOrOutdated.length) {
    const details = [
      ...staleFiles.map((file) => `stale: standalone/${file}`),
      ...missingOrOutdated.map((file) => `outdated: standalone/${file}`),
    ];
    console.error(`Standalone component entries are not up to date:\n${details.join('\n')}`);
    process.exit(1);
  }
  console.log(`Standalone component entries are up to date (${componentFiles.length} components).`);
  process.exit(0);
}

fs.mkdirSync(standaloneDir, { recursive: true });
for (const file of staleFiles) {
  fs.rmSync(path.join(standaloneDir, file));
}
for (const [file, content] of expected) {
  fs.writeFileSync(path.join(standaloneDir, file), content);
}

console.log(`Generated ${componentFiles.length} standalone component entries plus core.css.`);
